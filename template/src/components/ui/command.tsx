// PATCH vs the shadcn `base-vega` registry — re-apply after any `ui-add`.
//
// Upstream writes the highlight as `data-selected:…`, and Tailwind v4 compiles
// that bare variant to `[data-selected]` — attribute PRESENCE. But cmdk renders
// `"data-selected": !!selected`, and React stringifies a data-attribute, so an
// UNselected row still carries `data-selected="false"`. The attribute is
// therefore always present and every row lit up at once.
//
// `data-[selected=true]:` is the value match this actually needs. It is the
// same exemption `data-orientation` gets in
// .agents/rules/architecture-ui-primitives.md: cmdk sets a real value
// attribute, not a Base UI boolean one, so the bracketed form is correct here
// rather than the Radix shape that rule bans.
//
// Verified against the repo's own Tailwind 4.3.3 — the bare variant compiles to
// an `[data-selected]` attribute-presence selector, the bracketed one to
// `[data-selected="true"]`. That probe is deliberately NOT written out as real
// utility strings here: Tailwind scans comments too, so a sample class in this
// block would be compiled into the app's stylesheet as dead CSS.
function CommandItem({
  className,
  children,
  ...props
}: React.ComponentProps<typeof CommandPrimitive.Item>) {
  return (
    <CommandPrimitive.Item
      data-slot="command-item"
      className={cn(
        "group/command-item relative flex cursor-default items-center gap-2 rounded-sm px-2 py-1.5 text-sm outline-hidden select-none in-data-[slot=dialog-content]:rounded-lg! data-[disabled=true]:pointer-events-none data-[disabled=true]:opacity-50 data-[selected=true]:bg-muted data-[selected=true]:text-foreground [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4 data-[selected=true]:**:[svg]:text-foreground",
        className,
      )}
      {...props}
    >
      {children}
      <CheckIcon className="ml-auto opacity-0 group-has-data-[slot=command-shortcut]/command-item:hidden group-data-[checked=true]/command-item:opacity-100" />
    </CommandPrimitive.Item>
  );
}

function CommandShortcut({
  className,
  ...props
}: React.ComponentProps<"span">) {
  return (
    <span
      data-slot="command-shortcut"
      className={cn(
        // Same upstream patch as `CommandItem` above — the group variant reads
        // the same always-present attribute, so the shortcut was permanently
        // rendering in its highlighted colour.
        "ml-auto text-xs tracking-widest text-muted-foreground group-data-[selected=true]/command-item:text-foreground",
        className,
      )}
      {...props}
    />
  );
}

